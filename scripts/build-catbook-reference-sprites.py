"""Measure both generated reference atlases without changing their pixels."""
import json
from pathlib import Path
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
NAMES=['戴着站长帽迎接朋友','趴在窗边看风景','探出脑袋看风景','戴着铃铛端正坐着','捧着茶杯等朋友','钻进纸袋里玩耍','顶着纸帽慢慢走','翘着尾巴钻灌木','探出脑袋和小爪爪','窝在箱子里休息','眯着眼睛打盹','穿着忍者装守望']
MOTIONS=['sit','peek','peek','sit','sit','play','watch','scratch','peek','peek','peek','sit']

def bounds(texture, rows):
    im=Image.open(ROOT/'public/assets/catbook'/f'{texture}.png')
    alpha=im.getchannel('A'); pixels=list(alpha.get_flattened_data()); bands=[]
    for y in range(im.height):
        if sum(v>=96 for v in pixels[y*im.width:(y+1)*im.width])>3:
            if not bands or y-bands[-1][1]>3: bands.append([y,y])
            else: bands[-1][1]=y
    assert len(bands)==rows, (texture,bands)
    cuts=[0]+[(bands[i][1]+bands[i+1][0])//2 for i in range(rows-1)]+[im.height]
    result=[]
    for index in range(rows*4):
        col,row=index%4,index//4
        x=col*im.width//4; right=(col+1)*im.width//4; y=cuts[row]
        crop=alpha.crop((x,y,right,cuts[row+1])).point(lambda v:255 if v>=96 else 0)
        box=crop.getbbox(); assert box
        result.append([x+box[0],y+box[1],x+box[2],y+box[3]])
    return im.size,result

def frame(size, rect, target=None):
    left,top,right,bottom=rect
    width,height=target or (right-left+8,bottom-top+8)
    x=(left+right-width)/2; y=bottom-height+4
    return {'ratio':f'{width} / {height}','baseline':(height-4)/height*100,
            'backgroundSize':f'{size[0]/width*100:.6f}% {size[1]/height*100:.6f}%',
            'position':f'{x/(size[0]-width)*100:.6f}% {y/(size[1]-height)*100:.6f}%'}

size,rects=bounds('reference-cats-v1',3); poses=[]
for i,rect in enumerate(rects):
    item=frame(size,rect); width,height=map(int,item['ratio'].split('/'))
    poses.append({'name':NAMES[i],'motion':MOTIONS[i],'texture':'reference-cats-v1',
                  'portraitWidth':min(1,width/height)*100,'ratio':item['ratio'],
                  'baseline':item['baseline'],'backgroundSize':item['backgroundSize'],
                  'backgroundPosition':item['position']})
size,rects=bounds('reference-walking-v1',6); walks=[]
# Cloudcap's row has tiny fragments from adjacent tails at the cell edges.
# Use the connected character bounds so its patrol never shows those fragments.
rects[6]=[564,355,765,537]
rects[18]=[563,1114,765,1283]
for i in range(12):
    a,b=rects[i],rects[i+12]
    target=(max(a[2]-a[0],b[2]-b[0])+8,max(a[3]-a[1],b[3]-b[1])+8)
    phase_a,phase_b=frame(size,a,target),frame(size,b,target)
    walks.append({'texture':'reference-walking-v1','ratio':phase_a['ratio'],
                  'backgroundSize':phase_a['backgroundSize'],'a':phase_a['position'],'b':phase_b['position']})
text='// Generated by scripts/build-catbook-reference-sprites.py; original PNG alpha stays intact.\n'
for name,values in [('REFERENCE_CAT_POSES',poses),('REFERENCE_CAT_WALKS',walks)]:
    text+=f'export const {name}=Object.freeze('+json.dumps(values,ensure_ascii=False,indent=2)+'.map(Object.freeze));\n'
(ROOT/'src/catbook-reference-sprites.js').write_text(text)
print('Measured 12 scene poses and 24 walking frames.')
